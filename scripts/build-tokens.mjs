#!/usr/bin/env node
/**
 * OVS Token Builder
 * -------------------------------------------------------------
 * Single source of truth: ../tokens.json
 *
 * Generates:
 *   1. resources/css/ovs-tokens.generated.css   (CSS custom properties, HSL for shadcn compat)
 *   2. resources/js/ovs/tokens.generated.js     (Tailwind theme.extend fragment)
 *   3. resources/js/ovs/tokens.js               (Plain JS token object for runtime/canvas/charts)
 *   4. resources/js/ovs/tokens.ts               (TypeScript typed export as ovsTokens)
 *
 * Run: node scripts/build-tokens.mjs
 * DO NOT hand-edit the generated files — edit tokens.json instead.
 */
import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(path.join(__dirname, "..", "tokens.json"), "utf-8"));

// ---- helpers -----------------------------------------------------------
function hexToHsl(hex) {
  if (typeof hex !== "string" || !hex.startsWith("#")) return hex;
  hex = hex.replace("#", "");
  if (hex.length !== 6) return hex;
  const r = parseInt(hex.substring(0, 2), 16) / 255;
  const g = parseInt(hex.substring(2, 4), 16) / 255;
  const b = parseInt(hex.substring(4, 6), 16) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h, s, l = (max + min) / 2;
  if (max === min) { h = s = 0; }
  else {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r: h = (g - b) / d + (g < b ? 6 : 0); break;
      case g: h = (b - r) / d + 2; break;
      case b: h = (r - g) / d + 4; break;
    }
    h /= 6;
  }
  return `${Math.round(h * 360)} ${Math.round(s * 100)}% ${Math.round(l * 100)}%`;
}

function flattenColors(obj, prefix = "") {
  const out = {};
  for (const [key, val] of Object.entries(obj)) {
    const name = prefix ? `${prefix}-${key}` : key;
    if (typeof val === "string") out[name] = val;
    else Object.assign(out, flattenColors(val, name));
  }
  return out;
}

// ---- 1. CSS custom properties ------------------------------------------
const allColorTokens = {
  ...tokens.colors,
  glass: tokens.glass,
  mesh: tokens.mesh,
  table: tokens.table.colors,
  status: tokens.status,
  skeleton: {
    bg: tokens.skeleton.bg,
    highlight: tokens.skeleton.highlight,
  },
  emptyState: tokens.emptyState,
};

const flatColors = flattenColors(allColorTokens);
let css = `/* AUTO-GENERATED by scripts/build-tokens.mjs — DO NOT EDIT. Edit tokens.json instead. */\n@layer base {\n  :root {\n`;
for (const [name, hex] of Object.entries(flatColors)) {
  css += `    --ovs-${name}: ${hex};\n`;
  if (typeof hex === "string" && hex.startsWith("#")) {
    css += `    --ovs-${name}-hsl: ${hexToHsl(hex)};\n`;
  }
}
css += `    --ovs-radius: ${tokens.radius.md};\n`;

// ---- 1b. Canonical OralCares tokens (oc-*) ------------------------------
// Phase 2, additive only. Everything emitted above is untouched; these are new
// custom properties that no consumer reads yet. `tokens.oc` carries the values
// measured from the rendered CRM + Marketing UI, which is why several of them
// disagree with the older `ovs-*` declarations they will eventually replace.
const oc = tokens.oc ?? {};

/** Emits a font step's parts, skipping any the token deliberately leaves unset. */
function ocTypeVars(group, name, step) {
  let out = `    --oc-${group}-${name}-size: ${step.size};\n`;
  if (step.lineHeight !== undefined) {
    out += `    --oc-${group}-${name}-line-height: ${step.lineHeight};\n`;
  }
  if (step.letterSpacing !== undefined) {
    out += `    --oc-${group}-${name}-letter-spacing: ${step.letterSpacing};\n`;
  }
  if (step.fontWeight !== undefined) {
    out += `    --oc-${group}-${name}-font-weight: ${step.fontWeight};\n`;
  }
  return out;
}

if (oc.colors) {
  for (const [name, value] of Object.entries(flattenColors(oc.colors))) {
    css += `    --oc-${name}: ${value};\n`;
    if (typeof value === "string" && value.startsWith("#")) {
      css += `    --oc-${name}-hsl: ${hexToHsl(value)};\n`;
    }
  }
}
for (const [name, step] of Object.entries(oc.typography?.text ?? {})) {
  css += ocTypeVars("text", name, step);
}
for (const [name, step] of Object.entries(oc.typography?.num ?? {})) {
  css += ocTypeVars("num", name, step);
}
for (const [name, value] of Object.entries(oc.radius ?? {})) {
  css += `    --oc-radius-${name}: ${value};\n`;
}
for (const [group, steps] of Object.entries(oc.sizing ?? {})) {
  for (const [name, value] of Object.entries(steps)) {
    css += `    --oc-${group}-${name}: ${value};\n`;
  }
}

css += `  }\n}\n`;

mkdirSync(path.join(__dirname, "..", "resources", "css"), { recursive: true });
writeFileSync(path.join(__dirname, "..", "resources", "css", "ovs-tokens.generated.css"), css);

// ---- 2. Tailwind theme.extend fragment ----------------------------------
function nestColors(obj) {
  const out = {};
  for (const [key, val] of Object.entries(obj)) {
    if (typeof val === "string") {
      out[key] = val;
    } else {
      out[key] = nestColors(val);
    }
  }
  return out;
}

const fontSizeEntries = Object.entries(tokens.typography.fontSize).map(([key, v]) => {
  return `    ${JSON.stringify(key)}: [${JSON.stringify(v.size)}, { lineHeight: ${JSON.stringify(v.lineHeight)}, letterSpacing: ${JSON.stringify(v.letterSpacing)}, fontWeight: ${JSON.stringify(v.fontWeight)} }],`;
}).join("\n");

/**
 * Canonical OralCares Tailwind fragments.
 *
 * A step that sets only `size` emits a bare font-size, exactly like the
 * `text-[13px]` it replaces — Tailwind would otherwise attach a line-height the
 * current markup does not have, and Phase 2 must not move a single pixel.
 */
function ocFontSizeEntry(key, step) {
  const options = {};
  if (step.lineHeight !== undefined) { options.lineHeight = step.lineHeight; }
  if (step.letterSpacing !== undefined) { options.letterSpacing = step.letterSpacing; }
  if (step.fontWeight !== undefined) { options.fontWeight = step.fontWeight; }
  return Object.keys(options).length > 0
    ? `    ${JSON.stringify(key)}: [${JSON.stringify(step.size)}, ${JSON.stringify(options)}],`
    : `    ${JSON.stringify(key)}: ${JSON.stringify(step.size)},`;
}

const ocFontSizeEntries = [
  ...Object.entries(oc.typography?.text ?? {}).map(([k, v]) => ocFontSizeEntry(`oc-${k}`, v)),
  ...Object.entries(oc.typography?.num ?? {}).map(([k, v]) => ocFontSizeEntry(`oc-num-${k}`, v)),
].join("\n");

const ocFontFamily = Object.fromEntries(
  Object.entries(oc.typography?.fontFamily ?? {}).map(([k, v]) => [`oc-${k}`, v])
);

const ocRadius = Object.fromEntries(
  Object.entries(oc.radius ?? {}).map(([k, v]) => [`oc-${k}`, v])
);

const ocSpacing = Object.fromEntries(
  Object.entries(oc.sizing ?? {}).flatMap(([group, steps]) =>
    Object.entries(steps).map(([k, v]) => [`oc-${group}-${k}`, v])
  )
);

const flatRadius = {
  ovs: tokens.radius,
  ...Object.fromEntries(Object.entries(tokens.radius).map(([k, v]) => [`ovs-${k}`, v])),
  ...ocRadius
};

const flatShadows = {
  ovs: tokens.shadows,
  ...Object.fromEntries(Object.entries(tokens.shadows).map(([k, v]) => [`ovs-${k}`, v]))
};

const jsTailwindOut = `// AUTO-GENERATED by scripts/build-tokens.mjs — DO NOT EDIT. Edit tokens.json instead.
// Import this into tailwind.config.js and spread into theme.extend.
module.exports = {
  colors: {
    ovs: ${JSON.stringify(nestColors(allColorTokens), null, 6).replace(/\n/g, "\n  ")},
    oc: ${JSON.stringify(nestColors(oc.colors ?? {}), null, 6).replace(/\n/g, "\n  ")}
  },
  backdropBlur: {
    'ovs-sm': ${JSON.stringify(tokens.glass.blurSm)},
    'ovs-md': ${JSON.stringify(tokens.glass.blurMd)},
    'ovs-lg': ${JSON.stringify(tokens.glass.blurLg)}
  },
  fontFamily: ${JSON.stringify({ ...tokens.typography.fontFamily, ...ocFontFamily }, null, 4).replace(/\n/g, "\n  ")},
  fontSize: {
${fontSizeEntries}${ocFontSizeEntries ? `\n${ocFontSizeEntries}` : ""}
  },
  spacing: ${JSON.stringify({ ...tokens.spacing, ...ocSpacing }, null, 4).replace(/\n/g, "\n  ")},
  borderRadius: ${JSON.stringify(flatRadius, null, 4).replace(/\n/g, "\n  ")},
  boxShadow: ${JSON.stringify(flatShadows, null, 4).replace(/\n/g, "\n  ")},
  zIndex: ${JSON.stringify(tokens.zIndex, null, 4).replace(/\n/g, "\n  ")}
};
`;

mkdirSync(path.join(__dirname, "..", "resources", "js", "ovs"), { recursive: true });
writeFileSync(path.join(__dirname, "..", "resources", "js", "ovs", "tokens.generated.js"), jsTailwindOut);

