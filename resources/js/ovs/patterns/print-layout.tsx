import React from 'react';
import { Printer, Download } from 'lucide-react';
import { cn } from '@/lib/utils';
import { Button } from '@/ovs/primitives/button';
import '@/ovs/utils/print.css';

export interface PrintLayoutProps {
  title?: string;
  subtitle?: string;
  documentNumber?: string;
  date?: string;
  actions?: React.ReactNode;
  children: React.ReactNode;
  className?: string;
}

export function PrintLayout({
  title = 'Document',
  subtitle,
  documentNumber,
  date,
  actions,
  children,
  className,
}: PrintLayoutProps) {
  const handlePrint = () => {
    window.print();
  };

  return (
    <div className={cn('space-y-6', className)}>
      {/* Top Action Bar (hidden in print) */}
      <div className="no-print p-4 bg-white border border-ovs-border-subtle rounded-2xl flex flex-wrap items-center justify-between gap-4 shadow-2xs">
        <div>
          <span className="text-xs font-bold text-ovs-primary block">{title}</span>
          {subtitle && <span className="text-[11px] text-ovs-secondary block mt-0.5">{subtitle}</span>}
        </div>
        <div className="flex items-center gap-2">
          {actions}
          <Button variant="primary" size="sm" onClick={handlePrint} className="gap-1.5">
            <Printer className="w-4 h-4" />
            <span>Print Document</span>
          </Button>
        </div>
      </div>

      {/* Print Document Area */}
      <div className="print-area p-8 bg-white border border-ovs-border-subtle rounded-2xl shadow-2xs space-y-6 font-sans">
        {/* Document Header */}
        <div className="flex justify-between items-start border-b border-ovs-border-subtle pb-6">
          <div>
            <span className="text-lg font-bold text-ovs-primary tracking-tight block">{title}</span>
            {subtitle && <span className="text-xs text-ovs-secondary block mt-1">{subtitle}</span>}
          </div>
          {(documentNumber || date) && (
            <div className="text-right text-xs">
              {documentNumber && <span className="font-mono font-bold text-ovs-primary block">{documentNumber}</span>}
              {date && <span className="text-ovs-secondary block mt-0.5">{date}</span>}
            </div>
          )}
        </div>

        {/* Printable Body Content */}
        <div className="print-content text-xs text-ovs-primary leading-relaxed space-y-4">
          {children}
        </div>

        {/* Printable Footer */}
        <div className="pt-6 border-t border-ovs-border-subtle flex justify-between items-center text-[10px] text-ovs-secondary font-mono">
          <span>Generated by OralCares Enterprise Platform</span>
          <span>Confidential Commercial Document</span>
        </div>
      </div>
    </div>
  );
}
