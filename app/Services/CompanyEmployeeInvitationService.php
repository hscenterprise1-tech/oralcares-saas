<?php

namespace App\Services;

use App\EmploymentStatus;
use App\Mail\CompanyEmployeeInvitationMail;
use App\Models\CompanyEmployee;
use App\Models\CompanyEmployeeActivity;
use App\Models\CompanyEmployeeInvitation;
use App\Models\User;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Mail;
use Illuminate\Support\Str;
use InvalidArgumentException;
use LogicException;

class CompanyEmployeeInvitationService
{
    /**
     * Generate and send a new secure invitation to an employee.
     */
    public function generateInvitation(CompanyEmployee $employee, string $email, User $createdBy): CompanyEmployeeInvitation
    {
        $employee->update(['employment_status' => EmploymentStatus::Invited]);

        $invitation = CompanyEmployeeInvitation::create([
            'token' => Str::random(40),
            'company_employee_id' => $employee->id,
            'email' => $email,
            'expires_at' => now()->addDays(3),
            'created_by' => $createdBy->id,
        ]);

        $this->logActivity($employee, 'Invitation Created', 'Invitation generated by '.$createdBy->name);

        Mail::to($email)->send(new CompanyEmployeeInvitationMail($invitation));

        $this->logActivity($employee, 'Invitation Sent', 'Invitation sent to '.$email);

        return $invitation;
    }

    /**
     * Validate an invitation token and return the invitation if valid.
     *
     * @throws InvalidArgumentException
     */
    public function validateToken(string $token): CompanyEmployeeInvitation
    {
        $invitation = CompanyEmployeeInvitation::where('token', $token)->first();

        if (! $invitation) {
            throw new InvalidArgumentException('Invalid invitation token.');
        }

        if ($invitation->accepted_at !== null) {
            throw new LogicException('This invitation has already been accepted.');
        }

        if ($invitation->revoked_at !== null) {
            $this->logActivity($invitation->employee, 'Invitation Expired', 'Attempted to use a revoked invitation.');
            throw new LogicException('This invitation has been revoked.');
        }

        if ($invitation->isExpired()) {
            $this->logActivity($invitation->employee, 'Invitation Expired', 'Invitation token expired.');
            throw new LogicException('This invitation has expired.');
        }

        return $invitation;
    }

    /**
     * Accept the invitation, verify email, set password, and activate employee.
     */
    public function acceptInvitation(string $token, string $password): CompanyEmployee
    {
        $invitation = $this->validateToken($token);
        $employee = $invitation->employee;
        $user = $employee->user;

        $user->password = Hash::make($password);
        $user->email_verified_at = now();
        $user->save();

        $invitation->update(['accepted_at' => now()]);

        $employee->update(['employment_status' => EmploymentStatus::Active]);

        $this->logActivity($employee, 'Invitation Accepted', 'Invitation token successfully accepted.');
        $this->logActivity($employee, 'Password Created', 'Employee successfully chose their password.');

        return $employee;
    }

    /**
     * Revoke an invitation.
     */
    public function revokeInvitation(CompanyEmployeeInvitation $invitation, User $revokedBy): void
    {
        if ($invitation->accepted_at !== null) {
            throw new LogicException('Cannot revoke an already accepted invitation.');
        }

        $invitation->update(['revoked_at' => now()]);
        $invitation->employee->update(['employment_status' => EmploymentStatus::Suspended]);

        $this->logActivity($invitation->employee, 'Invitation Revoked', 'Invitation revoked by '.$revokedBy->name);
    }

    /**
     * Resend an invitation (invalidates the old one and generates a new one).
     */
    public function resendInvitation(CompanyEmployeeInvitation $invitation, User $resentBy): CompanyEmployeeInvitation
    {
        if ($invitation->accepted_at !== null) {
            throw new LogicException('Cannot resend an already accepted invitation.');
        }

        $invitation->update(['revoked_at' => now()]);

        return $this->generateInvitation($invitation->employee, $invitation->email, $resentBy);
    }

    /**
     * Log an audit activity event.
     */
    public function logActivity(CompanyEmployee $employee, string $event, ?string $description = null): void
    {
        CompanyEmployeeActivity::create([
            'company_employee_id' => $employee->id,
            'event' => $event,
            'description' => $description,
            'ip_address' => request()->ip(),
            'user_agent' => request()->userAgent(),
        ]);
    }
}
